const K_CG_EVENT_SOURCE_STATE_COMBINED_SESSION_STATE: u32 = 0;
const K_CG_HID_EVENT_TAP: u32 = 0;
const K_CG_EVENT_FLAG_MASK_COMMAND: u64 = 0x0010_0000;
const K_VK_ANSI_V: u16 = 0x09;

const CONCEALED_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
    "org.nspasteboard.TransientType",
    "com.agilebits.onepassword",
    "de.plessmann.macpass",
];

unsafe fn nsstring_to_string(ns_str: id) -> Option<String> {
    if ns_str == nil {
        return None;
    }
    let c_str: *const std::os::raw::c_char = msg_send![ns_str, UTF8String];
    if c_str.is_null() {
        None
    } else {
        Some(CStr::from_ptr(c_str).to_string_lossy().into_owned())
    }
}

unsafe fn nsstring_autoreleased(s: &str) -> id {
    let Ok(cstr) = CString::new(s) else {
        return nil;
    };
    msg_send![class!(NSString), stringWithUTF8String: cstr.as_ptr()]
}

pub fn get_frontmost_app() -> Option<FrontmostAppInfo> {
    autoreleasepool(|| unsafe {
        let workspace: id = msg_send![class!(NSWorkspace), sharedWorkspace];
        if workspace == nil {
            return None;
        }
        let app: id = msg_send![workspace, frontmostApplication];
        if app == nil {
            return None;
        }
        let bundle_ns: id = msg_send![app, bundleIdentifier];
        let name_ns: id = msg_send![app, localizedName];
        let pid: i32 = msg_send![app, processIdentifier];

        Some(FrontmostAppInfo {
            bundle_id: nsstring_to_string(bundle_ns),
            name: nsstring_to_string(name_ns),
            pid,
            window_handle: 0,
        })
    })
}

pub fn activate_app(app_info: &FrontmostAppInfo) -> bool {
    if app_info.pid <= 0 {
        return false;
    }
    autoreleasepool(|| unsafe {
        let app: id = msg_send![
            class!(NSRunningApplication),
            runningApplicationWithProcessIdentifier: app_info.pid
        ];
        if app == nil {
            return false;
        }
        // NSApplicationActivateIgnoringOtherApps = 1 << 1
        let options: usize = 1 << 1;
        let ok: BOOL = msg_send![app, activateWithOptions: options];
        ok == YES
    })
}

pub fn get_clipboard_change_count() -> i64 {
    autoreleasepool(|| unsafe {
        let pasteboard: id = msg_send![class!(NSPasteboard), generalPasteboard];
        if pasteboard == nil {
            return 0;
        }
        let count: isize = msg_send![pasteboard, changeCount];
        count as i64
    })
}

pub fn is_clipboard_concealed() -> bool {
    autoreleasepool(|| unsafe {
        let pasteboard: id = msg_send![class!(NSPasteboard), generalPasteboard];
        if pasteboard == nil {
            return false;
        }
        let types: id = msg_send![pasteboard, types];
        if types == nil {
            return false;
        }
        let count: usize = msg_send![types, count];
        for idx in 0..count {
            let item: id = msg_send![types, objectAtIndex: idx];
            if let Some(type_name) = nsstring_to_string(item) {
                if CONCEALED_TYPES.iter().any(|&t| t == type_name) {
                    return true;
                }
            }
        }
        false
    })
}

pub fn read_platform_files_and_rtf() -> (Option<Vec<String>>, Option<Vec<u8>>) {
    autoreleasepool(|| unsafe {
        let pasteboard: id = msg_send![class!(NSPasteboard), generalPasteboard];
        if pasteboard == nil {
            return (None, None);
        }

        // 1. Check file URLs
        let url_class: *const Class = class!(NSURL);
        let classes: id = msg_send![class!(NSArray), arrayWithObject: url_class as id];
        let objects: id = msg_send![pasteboard, readObjectsForClasses: classes options: nil];

        let mut file_paths = Vec::new();
        if objects != nil {
            let count: usize = msg_send![objects, count];
            for idx in 0..count {
                let url: id = msg_send![objects, objectAtIndex: idx];
                if url != nil {
                    let is_file: BOOL = msg_send![url, isFileURL];
                    if is_file == YES {
                        let path_ns: id = msg_send![url, path];
                        if let Some(path) = nsstring_to_string(path_ns) {
                            if !path.is_empty() {
                                file_paths.push(path);
                            }
                        }
                    }
                }
            }
        }

        if !file_paths.is_empty() {
            return (Some(file_paths), None);
        }

        // 2. Check RTF data
        let rtf_type = nsstring_autoreleased("public.rtf");
        let rtf_data: id = if rtf_type != nil {
            msg_send![pasteboard, dataForType: rtf_type]
        } else {
            nil
        };

        let rtf_bytes = if rtf_data != nil {
            let len: usize = msg_send![rtf_data, length];
            let ptr: *const u8 = msg_send![rtf_data, bytes];
            if !ptr.is_null() && len > 0 {
                Some(std::slice::from_raw_parts(ptr, len).to_vec())
            } else {
                None
            }
        } else {
            None
        };

        (None, rtf_bytes)
    })
}

pub fn write_platform_files_and_rtf(
    files: Option<&[String]>,
    rtf: Option<&[u8]>,
    text: Option<&str>,
) -> bool {
    autoreleasepool(|| unsafe {
        let pasteboard: id = msg_send![class!(NSPasteboard), generalPasteboard];
        if pasteboard == nil {
            return false;
        }
        let _: isize = msg_send![pasteboard, clearContents];

        if let Some(paths) = files {
            if !paths.is_empty() {
                let urls: id = msg_send![class!(NSMutableArray), arrayWithCapacity: paths.len()];
                for path in paths {
                    let path_ns = nsstring_autoreleased(path);
                    if path_ns != nil {
                        let url: id = msg_send![class!(NSURL), fileURLWithPath: path_ns];
                        if url != nil {
                            let _: () = msg_send![urls, addObject: url];
                        }
                    }
                }
                let ok: BOOL = msg_send![pasteboard, writeObjects: urls];
                return ok == YES;
            }
        }

        let mut wrote_any = false;

        if let Some(rtf_bytes) = rtf {
            let ns_data: id = msg_send![
                class!(NSData),
                dataWithBytes: rtf_bytes.as_ptr()
                length: rtf_bytes.len()
            ];
            let rtf_type = nsstring_autoreleased("public.rtf");
            if ns_data != nil && rtf_type != nil {
                let ok: BOOL = msg_send![pasteboard, setData: ns_data forType: rtf_type];
                wrote_any |= ok == YES;
            }
        }

        if let Some(plain) = text {
            let plain_ns = nsstring_autoreleased(plain);
            let str_type = nsstring_autoreleased("public.utf8-plain-text");
            if plain_ns != nil && str_type != nil {
                let ok: BOOL = msg_send![pasteboard, setString: plain_ns forType: str_type];
                wrote_any |= ok == YES;
            }
        }

        wrote_any
    })
}

pub fn is_accessibility_trusted(prompt: bool) -> bool {
    unsafe {
        if !prompt {
            return AXIsProcessTrusted() != 0;
        }
        let key = CFString::wrap_under_get_rule(kAXTrustedCheckOptionPrompt);
        let value = CFBoolean::true_value();
        let options = CFDictionary::from_CFType_pairs(&[(key.as_CFType(), value.as_CFType())]);
        AXIsProcessTrustedWithOptions(options.as_concrete_TypeRef()) != 0
    }
}

pub fn open_accessibility_settings() {
    let _ = std::process::Command::new("open")
        .arg("x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility")
        .spawn();
}

pub fn simulate_paste_shortcut() {
    if !is_accessibility_trusted(false) {
        eprintln!("[PasteService] Accessibility permission not granted. Cmd+V skipped.");
        return;
    }

    unsafe {
        let source = CGEventSourceCreate(K_CG_EVENT_SOURCE_STATE_COMBINED_SESSION_STATE);
        if source.is_null() {
            return;
        }

        let key_down = CGEventCreateKeyboardEvent(source, K_VK_ANSI_V, true);
        let key_up = CGEventCreateKeyboardEvent(source, K_VK_ANSI_V, false);

        if !key_down.is_null() {
            CGEventSetFlags(key_down, K_CG_EVENT_FLAG_MASK_COMMAND);
            CGEventPost(K_CG_HID_EVENT_TAP, key_down);
            CFRelease(key_down);
        }
        if !key_up.is_null() {
            CGEventSetFlags(key_up, K_CG_EVENT_FLAG_MASK_COMMAND);
            CGEventPost(K_CG_HID_EVENT_TAP, key_up);
            CFRelease(key_up);
        }

        CFRelease(source);
    }
}
